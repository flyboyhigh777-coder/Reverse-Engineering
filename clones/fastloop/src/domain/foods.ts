const FOLD = (text: string): string => text.toLowerCase().replace(/ё/g, 'е').trim();

/**
 * Finds by any word in the name or the synonyms, so "помидор" reaches the
 * tomato salad and "рыба" reaches every fish. Matching ignores case and
 * treats ё as е, which people type interchangeably.
 */
export function searchFoods(query: string, limit = 40): readonly Food[] {
  const needle = FOLD(query);
  if (needle === '') return FOODS.slice(0, limit);
  const words = needle.split(/\s+/).filter(Boolean);
  const scored: { food: Food; score: number }[] = [];
  for (const item of FOODS) {
    const hay = FOLD([item.name, ...(item.also ?? [])].join(' '));
    if (!words.every((word) => hay.includes(word))) continue;
    // A name that starts with the query is what the person usually meant.
    const score = FOLD(item.name).startsWith(needle) ? 0 : hay.indexOf(needle) >= 0 ? 1 : 2;
    scored.push({ food: item, score });
  }
  return scored.sort((a, b) => a.score - b.score || a.food.name.localeCompare(b.food.name, 'ru')).slice(0, limit).map((s) => s.food);
}

export function foodById(id: string): Food | undefined {
  return FOODS.find((item) => item.id === id);
}


export interface Portion {
  readonly label: string;
  readonly grams: number;
}

export interface Food {
  readonly id: string;
  readonly name: string;
  readonly group: FoodGroup;
  readonly per100g: Macros;
  /** Named portions, so nobody has to weigh an egg. */
  readonly portions: readonly Portion[];
  /** Extra words that should find this item. */
  readonly also?: readonly string[];
}

/** kcal, protein, fat, carbs, fibre — per 100 g. */
type Composition = readonly [number, number, number, number, number];

function food(
  id: string,
  name: string,
  group: FoodGroup,
  [kcal, protein, fat, carbs, fiber]: Composition,
  portions: readonly Portion[],
  also?: readonly string[],
): Food {
  return { id, name, group, per100g: { kcal, protein, fat, carbs, fiber }, portions, also };
}


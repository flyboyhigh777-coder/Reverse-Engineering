import type { Macros } from './recipes';

/**
 * The food table behind manual entry.
 *
 * Composition per 100 g, from standard reference tables, rounded to what a
 * kitchen scale can justify. Cooked weights are used wherever a thing is
 * eaten cooked — "рис" here is boiled rice, not dry grain, because that is
 * what ends up on the plate and confusing the two is the single largest
 * error people make when counting by hand.
 *
 * The numbers are approximations and the app says so everywhere they appear.
 * Fat content of meat, the oil a dish absorbed and the size of a home
 * portion all move the result more than the table's own precision does.
 *
 * Written as a table rather than as object literals: a hundred and thirty
 * entries of the same shape read better in columns, and the builder below
 * gives them their types back.
 */


import type { PlanId } from './types';

/**
 * What a window actually gets you, and what it costs.
 *
 * The apps in this category sell a window by listing effects: clarity of
 * mind, reduced inflammation, slowed ageing. Most of that is either measured
 * in mice, measured during a multi-day fast, or not measured at all. Dropping
 * the claims entirely would be the easy answer and the wrong one — people
 * want to know what they are doing this for. So every claim is kept and
 * labelled with how much is known about it, and the label is as visible as
 * the claim.
 */

/**
 * The kinds of claim a window can make. Named here rather than next to the
 * drawings, because what a benefit is about is domain vocabulary and the
 * glyph is only how it is painted.
 */
export type BenefitIcon =
  | 'fat' | 'insulin' | 'brain' | 'gut' | 'heart' | 'sleep' | 'energy'
  | 'autophagy' | 'muscle' | 'simple' | 'weight' | 'inflammation' | 'habit';

/** How much is known, in four honest steps. */
export type Evidence = 'сильное' | 'умеренное' | 'слабое' | 'механизм';


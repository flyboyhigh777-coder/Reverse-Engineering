export function recipeById(id: string): Recipe | undefined {
  return RECIPES.find((recipe) => recipe.id === id);
}

export function recipesByRegion(region: Region): readonly Recipe[] {
  return RECIPES.filter((recipe) => recipe.region === region);
}

/** Everything that is not tied to a cuisine — the region-neutral library. */
export function regionlessRecipes(): readonly Recipe[] {
  return RECIPES.filter((recipe) => recipe.region === undefined);
}
